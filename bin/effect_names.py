"""Read ToneLib's native preset summary on its private X display.

The worker preserves the private clipboard and never connects to the desktop's
display. Only the requested effect name leaves the worker; no preset parameters
or clipboard contents are logged or persisted.
"""
import json,os,re,subprocess,sys,time
from pathlib import Path


def parse_effect_names(text):
    if not isinstance(text,str) or len(text)>1024*1024:return None
    if 'ToneLib GFX' not in text[:200] or 'Effects chain:' not in text or '// Generated by ToneLib GFX ver.' not in text:return None
    names=re.findall(r'^\s*Effect:\s*"([^"\r\n]{1,100})"',text,re.M)
    return names if len(names)<=128 else None


class EffectNameReader:
    def __init__(self,log=None,clock=time.monotonic):
        self.log=log;self.clock=clock;self.process=None;self.name=None
        self.context=None;self.epoch=0;self.counter=0;self.pending=None
        self.due=0;self.buffer=b''

    def close(self):
        if self.process is not None:
            if self.process.poll() is None:
                self.process.terminate()
                try:self.process.wait(timeout=1)
                except subprocess.TimeoutExpired:self.process.kill();self.process.wait()
            self.process.stdin.close();self.process.stdout.close()
        self.process=None;self.pending=None;self.buffer=b'';self.name=None

    def _receive(self):
        if self.process is None:return
        try:
            data=os.read(self.process.stdout.fileno(),65536)
        except BlockingIOError:return
        if not data:self.close();return
        self.buffer+=data
        if len(self.buffer)>65536:self.close();return
        while b'\n' in self.buffer:
            line,self.buffer=self.buffer.split(b'\n',1)
            try:reply=json.loads(line)
            except (ValueError,UnicodeError):continue
            if self.pending is None or reply.get('id')!=self.pending[0]:continue
            if self.pending[1]==self.epoch:
                name=reply.get('name')
                self.name=name if isinstance(name,str) and 0<len(name)<=100 else None
            self.pending=None

    def update(self,effect,generation,window,env):
        now=self.clock();context=(effect,generation,window)
        if context!=self.context:
            self.context=context;self.epoch+=1;self.name=None;self.due=now+.2
        try:
            self._receive()
            if self.pending is not None and now>self.pending[2]:self.close();self.due=now+2
            if effect is None or window is None or env is None:return None
            if self.pending is None and now>=self.due:
                if self.process is None:
                    self.process=subprocess.Popen([os.environ.get('TSMA_PYTHON','/usr/bin/python3'),'-u',str(Path(__file__).resolve()),'--worker'],env=env,stdin=subprocess.PIPE,stdout=subprocess.PIPE,stderr=self.log or subprocess.DEVNULL)
                    os.set_blocking(self.process.stdout.fileno(),False)
                self.counter+=1
                request={'id':self.counter,'window':window,'effect':effect}
                self.process.stdin.write((json.dumps(request)+'\n').encode());self.process.stdin.flush()
                self.pending=(self.counter,self.epoch,now+4);self.due=now+2
        except (OSError,ValueError):
            self.close();self.due=now+2
        return self.name


def worker():
    import ctypes as C,select,signal
    import gi
    gi.require_version('Gtk','3.0')
    from gi.repository import Gtk,Gdk
    x=C.CDLL('libX11.so.6');xtest=C.CDLL('libXtst.so.6')
    x.XOpenDisplay.argtypes=[C.c_char_p];x.XOpenDisplay.restype=C.c_void_p
    x.XCloseDisplay.argtypes=[C.c_void_p];x.XFlush.argtypes=[C.c_void_p]
    x.XStringToKeysym.argtypes=[C.c_char_p];x.XStringToKeysym.restype=C.c_ulong
    x.XKeysymToKeycode.argtypes=[C.c_void_p,C.c_ulong];x.XKeysymToKeycode.restype=C.c_uint
    x.XGetInputFocus.argtypes=[C.c_void_p,C.POINTER(C.c_ulong),C.POINTER(C.c_int)]
    x.XQueryKeymap.argtypes=[C.c_void_p,C.c_void_p]
    x.XInternAtom.argtypes=[C.c_void_p,C.c_char_p,C.c_int];x.XInternAtom.restype=C.c_ulong
    x.XGetSelectionOwner.argtypes=[C.c_void_p,C.c_ulong];x.XGetSelectionOwner.restype=C.c_ulong
    xtest.XTestFakeKeyEvent.argtypes=[C.c_void_p,C.c_uint,C.c_int,C.c_ulong]
    display=x.XOpenDisplay(None)
    if not display:raise RuntimeError('ToneLib private display unavailable')
    clipboard=Gtk.Clipboard.get(Gdk.SELECTION_CLIPBOARD)
    selection=x.XInternAtom(display,b'CLIPBOARD',0)
    running=True
    def stop(*_):
        nonlocal running
        running=False
    signal.signal(signal.SIGTERM,stop);signal.signal(signal.SIGINT,stop)
    def events():
        while Gtk.events_pending():Gtk.main_iteration_do(False)
    def read_names(window):
        focus=C.c_ulong();revert=C.c_int();x.XGetInputFocus(display,C.byref(focus),C.byref(revert))
        keys=C.create_string_buffer(32);x.XQueryKeymap(display,keys)
        # Do not steal focus from dialogs, SooperLooper, or a user typing.
        if focus.value!=window or any(keys.raw):return None
        previous=clipboard.wait_for_text()
        if previous is None and x.XGetSelectionOwner(display,selection):return None
        marker='TSMA private preset query '+str(time.monotonic_ns())
        clipboard.set_text(marker,-1);events()
        def key(symbol,pressed):
            code=x.XKeysymToKeycode(display,x.XStringToKeysym(symbol))
            if not code:raise RuntimeError('Private keyboard unavailable')
            xtest.XTestFakeKeyEvent(display,code,pressed,0);x.XFlush(display)
        text=marker
        try:
            key(b'Control_L',1);key(b'c',1);key(b'c',0);key(b'Control_L',0)
            deadline=time.monotonic()+.8
            while running and time.monotonic()<deadline:
                events();text=clipboard.wait_for_text()
                names=parse_effect_names(text)
                if names is not None:return names
                if text!=marker:return None
                time.sleep(.02)
            return None
        finally:
            # Preserve user copies made during the query instead of replacing
            # unrelated new text. The idle GTK loop serves the restored text.
            current=clipboard.wait_for_text()
            if current==marker or (current==text and parse_effect_names(text) is not None):
                if previous is None:clipboard.clear()
                else:clipboard.set_text(previous,-1)
    try:
        while running:
            events()
            if not select.select([sys.stdin],[],[],.02)[0]:continue
            line=sys.stdin.readline()
            if not line:break
            request=json.loads(line)
            effect=request.get('effect');window=request.get('window')
            name=None
            if type(effect) is int and 0<=effect<128 and type(window) is int and window>1:
                names=read_names(window)
                if names is not None and effect<len(names):name=names[effect]
            print(json.dumps({'id':request.get('id'),'name':name},ensure_ascii=False),flush=True)
    finally:x.XCloseDisplay(display)


if __name__=='__main__' and sys.argv[1:]==['--worker']:worker()

import json,os,sys,unittest
from pathlib import Path
from types import SimpleNamespace
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'bin'))
from effect_names import EffectNameReader,parse_effect_names


class EffectNames(unittest.TestCase):
 def test_native_summary_keeps_chain_order_and_unicode(self):
  summary='ToneLib GFX (Firmware ver. 4.0)\nEffects chain:\n{\n Effect: "T-Scream" (Drive), active - "yes"\n Effect: "Écho" (Delay), active - "no"\n};\n// Generated by ToneLib GFX ver. 4.9.0'
  self.assertEqual(parse_effect_names(summary),['T-Scream','Écho'])
  self.assertIsNone(parse_effect_names(summary.split('// Generated')[0]))
 def test_unrelated_clipboard_and_oversized_data_are_rejected(self):
  for value in (None,'ordinary user clipboard','Effect: "Delay"','ToneLib GFX'+'x'*1048576):
   self.assertIsNone(parse_effect_names(value))
 def test_late_reply_cannot_show_name_from_previous_preset(self):
  reader=EffectNameReader(clock=lambda:0)
  read,write=os.pipe();stream=os.fdopen(read,'rb',buffering=0);self.addCleanup(stream.close);self.addCleanup(os.close,write)
  os.set_blocking(read,False)
  reader.process=SimpleNamespace(stdout=stream)
  reader.context=(0,1,42);reader.epoch=1;reader.pending=(7,1,4)
  os.write(write,(json.dumps({'id':7,'name':'Old preset effect'})+'\n').encode())
  self.assertIsNone(reader.update(0,2,42,{}))
  self.assertIsNone(reader.pending)
 def test_valid_reply_updates_name(self):
  reader=EffectNameReader(clock=lambda:0)
  read,write=os.pipe();stream=os.fdopen(read,'rb',buffering=0);self.addCleanup(stream.close);self.addCleanup(os.close,write)
  os.set_blocking(read,False)
  reader.process=SimpleNamespace(stdout=stream)
  reader.context=(1,1,42);reader.epoch=1;reader.pending=(7,1,4);reader.due=2
  os.write(write,b'{"id":7,"name":"Fd Deluxe"}\n')
  self.assertEqual(reader.update(1,1,42,{}),'Fd Deluxe')


if __name__=='__main__':unittest.main()
